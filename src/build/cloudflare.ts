import { readFile, writeFile } from 'node:fs/promises';
import type { AstroIntegrationLogger } from 'astro';
import type { MarkdownWorkerOptions } from '../cloudflare/worker.js';
import type { RoutingConfig } from '../core/routing.js';
import type { CloudflareOptions } from '../options.js';

export interface CloudflareFilesOptions {
	/** Directory containing the generated assets (`dir` of `astro:build:done`). */
	dir: URL;
	cloudflare: Required<CloudflareOptions>;
	routing: RoutingConfig;
	contentSignal: string | null;
	contentNegotiation: boolean;
	buildOutput: 'static' | 'server';
	logger: AstroIntegrationLogger;
}

const MARKER = '# astro-agent-markdown';
const WORKER_FILE = '_worker.js';

/**
 * Writes the files Workers static assets need to serve Markdown well. Existing
 * `_headers` and `.assetsignore` files from `public/` are extended, not replaced.
 */
export async function writeCloudflareFiles({
	dir,
	cloudflare,
	routing,
	contentSignal,
	contentNegotiation,
	buildOutput,
	logger,
}: CloudflareFilesOptions): Promise<void> {
	if (cloudflare.headers && contentSignal) {
		await appendBlock(new URL('_headers', dir), headersRule(contentSignal));
	}
	if (!cloudflare.worker) {
		logger.info(
			'Cloudflare static assets serve .md and .txt files without `charset=utf-8`. See "Cloudflare without a Worker" in the README for the zone rules that add it.',
		);
		return;
	}

	if (!contentNegotiation) {
		logger.warn('`cloudflare.worker` is ignored because `contentNegotiation` is disabled.');
		return;
	}
	if (buildOutput === 'server') {
		logger.warn('`cloudflare.worker` is ignored for server output: the adapter provides the Worker.');
		return;
	}
	const workerFile = new URL(WORKER_FILE, dir);
	if ((await readText(workerFile)) !== undefined) {
		logger.warn(`Skipped ${WORKER_FILE}: the file already exists.`);
		return;
	}
	await writeFile(
		workerFile,
		workerSource({
			base: routing.base,
			outputPath: routing.outputPath,
			trailingSlash: routing.trailingSlash,
			buildFormat: routing.buildFormat,
			negotiation: cloudflare.negotiation,
			contentSignal,
		}),
	);
	await appendBlock(new URL('.assetsignore', dir), `${MARKER}\n${WORKER_FILE}`);
}

/**
 * Workers static assets serve `.md` files as `text/markdown`, without a
 * charset. Setting `Content-Type` here would also apply to the HTML 404 page
 * of a missing file; the Worker or a zone rule adds the charset instead.
 */
function headersRule(contentSignal: string): string {
	return [MARKER, '/*.md', `  Content-Signal: ${contentSignal}`].join('\n');
}

function workerSource(options: MarkdownWorkerOptions): string {
	return [
		'// Generated by astro-agent-markdown: serves Markdown to clients sending `Accept: text/markdown`.',
		"import { createMarkdownWorker } from 'astro-agent-markdown/cloudflare';",
		'',
		`export default createMarkdownWorker(${JSON.stringify(options)});`,
		'',
	].join('\n');
}

async function appendBlock(file: URL, block: string): Promise<void> {
	const current = await readText(file);
	if (current?.includes(MARKER)) return;
	await writeFile(file, current ? `${current.trimEnd()}\n\n${block}\n` : `${block}\n`);
}

async function readText(file: URL): Promise<string | undefined> {
	return readFile(file, 'utf8').catch(() => undefined);
}
